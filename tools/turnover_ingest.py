def _validate(q: str, vals: list) -> None:
    """写入前的三道硬校验（防常量列 / 防量纲错 / 防缺行业）。"""
    if len(vals) != C.NI:
        raise ValueError(f"{q}: 行业数 {len(vals)} ≠ {C.NI}")
    if not all(isinstance(v, (int, float)) and v > 0 for v in vals):
        raise ValueError(f"{q}: 存在非正数，疑似量纲错误（应为亿元）")
    if len(set(vals)) < C.NI - 1:
        raise ValueError(f"{q}: 取值高度重复，疑似误用『区间成交额』常量列")
    # 量纲合理性：单行业季度成交额应落在 500 ~ 2,000,000 亿元
    if not all(500 <= v <= 2_000_000 for v in vals):
        raise ValueError(f"{q}: 取值超出合理量纲区间 [500, 2e6] 亿元")


def main() -> None:
    os.makedirs(CACHE, exist_ok=True)
    print("=" * 74)
    print("写入 Wind 实测行业季度成交额")
    print("=" * 74)
    tot_prev = None
    for q, vals in MEASURED.items():
        _validate(q, vals)
        d = {ind: float(v) for ind, v in zip(_WIND_ORDER, vals)}
        d = {k: d[k] for k in C.INDUSTRIES}          # 统一到项目行业顺序
        dest = os.path.join(CACHE, f"turnover__{q}.json")
        with open(dest, "w", encoding="utf-8") as f:
            json.dump(d, f, ensure_ascii=False, indent=1)
        tot = sum(d.values())
        chg = "" if tot_prev is None else f"  ({tot / tot_prev - 1:+.1%})"
        print(f"  ✓ turnover {q}: 31/31 行业  全市场合计 {tot:>12,.0f} 亿元{chg}")
        tot_prev = tot
    print("\n提示：随后执行 `python tools/wind_fetch.py build` 重建 "
          "sw_industry_turnover.xlsx 及下游因子。")


if __name__ == "__main__":
    main()
