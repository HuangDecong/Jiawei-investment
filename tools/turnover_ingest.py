"""
turnover_ingest.py —— 把 Wind 实测的行业季度成交额写入抓取缓存

背景
----
本项目原 turnover 缓存仅覆盖 2022Q1 ~ 2024Q2。而基金持仓（holdings）覆盖
2024Q1 ~ 2026Q2，两者交集只有 2024Q1 ~ 2024Q2 **两个季度**。
后果：
  · F9  交易拥挤度（成交额占比分位）几乎全是 NaN；
  · F13 筹码盈利比例（滚动成交额加权）失效；
  · 冲击成本 / 策略容量模型（研究 4）无法建立参与率序列；
  · 数据质量报告登记「成交额缺口 80%」。

本次通过 Wind MCP `get_financial_data` 补齐 2024Q3 ~ 2026Q2 共 8 个季度，
使 turnover 覆盖与 holdings 完全对齐（2024Q1 ~ 2026Q2，共 10 期）。

Wind 返回的口径陷阱（已在取值时处理）
------------------------------------
同一响应里同时出现两列成交额：
  · 「区间成交额」（单位标注 万亿元）—— 实测为**固定值**，不随季度变化，
    判定为全历史累计或缓存列，**不可用**；
  · 「YYYY年第N季度成交额」（单位 亿元）—— 逐季变化，**这是正确列**。
本脚本只采用后者，并在写入前做「逐行业正数 + 非全等」校验，
防止误用常量列导致 F9/F13 静默失真。

用法
----
  python tools/turnover_ingest.py            # 写入缓存并重建 raw 文件
"""
