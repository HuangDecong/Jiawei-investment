LO, HI = -60.0, 80.0


def main() -> int:
    dry = "--dry-run" in sys.argv
    print("=" * 78)
    print("补齐 2019Q1~2021Q4 的 31 行业季度涨跌幅（Wind 实测）")
    print("=" * 78)
    bad = 0
    for q, vals in MEASURED.items():
        assert len(vals) == C.NI, f"{q}: 行业数 {len(vals)} ≠ {C.NI}"
        out = [v for v in vals if not (LO <= v <= HI)]
        if out:
            print(f"  ❌ {q}: 越界取值 {out}（合理区间 [{LO}, {HI}]%）")
            bad += 1
            continue
        d = {k: float(v) for k, v in zip(_WIND_ORDER, vals)}
        d = {k: d[k] for k in C.INDUSTRIES}     # 统一到项目行业顺序

        # 交叉校验：与既有旧值比对。
        # ⚠️ 本轮实测发现：2019Q1~2021Q4 的旧缓存**并不是这些季度的真实收益**，
        #    而是把 2022Q1 的 8 个行业数值原样复制了过来
        #    （农林牧渔 −13.4841、钢铁 −14.7373、有色金属 +3.8573 与 2022Q1 完全一致）
        #    —— 属早期抓取时的**整季错位/占位**缺陷。
        #    因此这里的差异**是预期的**，且以 Wind 新值为准。
        #    校验的作用是「记录并解释差异」，而不是拦截写入。
        p = os.path.join(CACHE, f"returns__{q}.json")
        cross = ""
        if os.path.exists(p):
            old = json.load(open(p, encoding="utf-8"))
            diffs = {k: abs(d[k] - old[k]) for k in old if k in d}
            mx = max(diffs.values()) if diffs else 0.0
            cross = f"｜旧值 {len(old)} 行业，最大差异 {mx:.4f}pct"
            if mx > 0.01:
                # 与 2022Q1 比对，确认旧值确实是错位复制
                p22 = os.path.join(CACHE, "returns__2022Q1.json")
                tag = ""
                if os.path.exists(p22):
                    o22 = json.load(open(p22, encoding="utf-8"))
                    same = sum(1 for k in old if k in o22 and abs(old[k] - o22[k]) < 1e-6)
                    if same >= max(1, len(old) - 1):
                        tag = f"（旧值实为 2022Q1 数据的错位复制：{same}/{len(old)} 项吻合）"
                print(f"  ⚠️  {q}: 旧值与 Wind 不符（最大 {mx:.4f}pct）{tag} → 以 Wind 新值为准")
        if not dry:
            with open(p, "w", encoding="utf-8") as f:
                json.dump(d, f, ensure_ascii=False, indent=1)
        avg = sum(vals) / len(vals)
        print(f"  ✓ {q}: {len(d)}/31 行业  均值 {avg:+.2f}%  "
              f"区间 [{min(vals):+.1f}, {max(vals):+.1f}]{cross}")

    print("-" * 78)
    print("✅ 全部 12 期已校验并写入"
          + ("（dry-run，未写入）" if dry else ""))
    print("\n提示：随后执行 `python tools/wind_fetch.py build` 重建 "
          "sw_industry_returns.xlsx。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
