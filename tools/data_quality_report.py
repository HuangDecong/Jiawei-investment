    A("")
    A("## 三、持仓序列体检")
    A("")
    A("| 季度 | 重仓合计(亿元) | 环比 | 电子占比 | Top1行业 | Top1占比 |")
    A("|---|---:|---:|---:|---|---:|")
    prev = None
    for q in qs:
        if q not in hold:
            continue
