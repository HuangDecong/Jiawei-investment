    A("| 非银金融 | 8.39% | **9.06%** | ~9% ✔ |")
    A("")
    A("旧值把 银行 抬到 22%、石油石化 抬到 8.8%，符合**总市值加权**的特征；")
    A("而沪深300 与所有主流宽基指数一样使用**自由流通市值加权（free-float）**。")
    A("即旧批次误取了「总市值口径」，与指数真实计算口径不符。")
    A("")
    A("**影响链（这才是关键）：**")
    A("")
    A("```")
    A("错误基准 → 超配比例 = 配置比例 − 基准权重 被系统性扭曲")
    A("         → 扩窗 Z-score 的历史标准差被压小")
    A("         → 长期低配行业出现 Z = +16.7 的伪极值、分位 = 100%")
    A("         → 分级规则误标为「极度拥挤」，而该行业实际深度低配")
    A("```")
    A("")
    A("**处理**：全部 9 期改用 Wind 重查的「成份股权重合计占比」口径，")
    A("逐期校验加总 = 100.000% ± 0.008。重查脚本 `tools/hs300_refetch.py`，")
    A("审计留痕 `data/wind_raw/hs300_weights_refetch_audit.xlsx`。")
    A("")
    A("### 风险 2：拥挤等级判定混淆「相对历史」与「绝对方向」（**本轮发现并已修复**）")
    A("")
    A("`F2_超配Zscore` 与 `F3_超配历史分位` 都是**相对该行业自身历史**的口径，")
    A("本身不含绝对方向。旧规则只用「分位 ≥ 90 ⇒ 极度拥挤」，在长期单边低配的")
    A("行业上会得出**与事实完全相反**的标签。实测（2026Q2，修正基准后）：")
