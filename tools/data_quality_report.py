    A("> | 主动权益三类 | 25,529 亿元 | **正确口径** |")
    A("> ")
    A("> 全口径使电子占比由 39.5% 被稀释至 38.1%（表面接近），但总市值虚高 82%，")
    A("> 直接污染 F1 超配比例、F12 配置系数与集中度 HHI。已全部按三类口径重抓。")
    A("")
    A("### 1.2 配置比例口径")
    A("")
    A("```")
