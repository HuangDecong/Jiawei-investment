    hold, hs = d["holdings"], d["hs300"]
    qs = d["quarters"]
    L: list[str] = []
    A = L.append

    A("# 数据质量与口径审计报告")
    A("")
    A(f"- 生成时刻：{datetime.now():%Y-%m-%d %H:%M:%S}")
