# 用于对照审计的旧值（银行/石油石化/食品饮料/非银金融）——证明口径被误用
_OLD_SUSPECT = {
    "2024Q2": {"银行": 22.16, "石油石化": 8.82, "非银金融": 8.39, "食品饮料": 7.33},
    "2026Q1": {"银行": 22.569891, "石油石化": 8.001709, "非银金融": 8.678797,
               "食品饮料": 5.192830},
}


def main() -> None:
    os.makedirs(CACHE, exist_ok=True)
    print("=" * 78)
    print("重建沪深300 行业权重（修正 总市值加权 → 自由流通市值加权 口径错误）")
    print("=" * 78)

    for q, d in MEASURED.items():
        s = sum(d.values())
        # 硬校验：指数权重必须加总 = 100%（允许 ±0.05 的四舍五入误差）
        if not (99.95 <= s <= 100.05):
            raise ValueError(f"{q}: 权重加总 {s:.3f}% ≠ 100%，疑似口径错误")
        bad = [k for k, v in d.items() if not (0.0 <= v <= 100.0)]
        if bad:
            raise ValueError(f"{q}: 权重越界 {bad}")
        # 写入 cache（与 wind_fetch 的 hs300 任务同名，build 时直接采用）
        with open(os.path.join(CACHE, f"hs300__{q}.json"), "w",
                  encoding="utf-8") as f:
            json.dump(d, f, ensure_ascii=False, indent=1)

        _o = _OLD_SUSPECT.get(q)
        _chg = ""
        if _o:
            _chg = "  ｜ 修正样本：" + "、".join(
                f"{k} {_o[k]:.2f}%→{d[k]:.2f}%" for k in _o if k in d)
        print(f"  ✓ hs300 {q}: {len(d):>2}/31 行业  加总 {s:7.3f}%{_chg}")

    # 落一份"口径修正留痕"到 raw，供审计
    rec = [dict(季度=q, 行业=k, 权重pct=v,
                数据来源="Wind", 数据表="沪深300成份行业权重（自由流通市值加权）",
                查询日期="2026-10-02",
                口径="沪深300指数成份股按申万一级行业权重合计占比",
                修正说明=("旧批次误用总市值口径，本轮全部重查替换"
                          if q in _OLD_SUSPECT else "与旧批次一致（该期旧值已正确）"))
          for q, d in MEASURED.items() for k, v in d.items()]
    try:
        import pandas as pd
        out = os.path.join(RAW, "hs300_weights_refetch_audit.xlsx")
        pd.DataFrame(rec).to_excel(out, index=False)
        print(f"\n  审计留痕 → {out}")
    except Exception as e:                                    # pragma: no cover
        print(f"  （审计文件写出跳过：{e}）")

    print("\n提示：随后执行 `python tools/wind_fetch.py build` 重建超配比例与全部下游。")


if __name__ == "__main__":
    main()
