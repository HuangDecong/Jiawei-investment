def _avail(IND: dict | None, key: str, kind: str = "ind") -> str:
    """动态统计因子当前可用期数，避免文档过期。"""
    if IND is None:
        return ""
    try:
        obj = IND.get(key) if kind == "ind" else None
        if obj is None:
            return ""
        if isinstance(obj, pd.DataFrame):
            n = int(obj.dropna(how="all").shape[0])
        else:
            n = int(obj.notna().sum())
        return f"（当前样本实际可用 <b>{n} 期</b>）"
    except Exception:
        return ""


