# ---------------------------------------------------------------------------
# 期数文案本地化：数据窗口变化后，「31 期」「14 期」「900 多个观测」都要跟着变。
# 统一在这里替换一次，避免每个页面各写一份、改数据时漏改。
# ---------------------------------------------------------------------------
def _localize_periods() -> None:
    try:
        import canon as _cn
        nq = len(_cn.quarters())
        nfq = len(_cn.full_quarters())
    except Exception:
        return
    if not nq:
        return
    # 因子/CSI 检验的可用期数 = 持仓期数 − 7（前 7 期配置分位不足 8 个观测）
    nqc = max(nq - 7, 1)
    reps = {"31 期": f"{nqc} 期",
            "15 期": f"{nfq} 期",
            "14 期": f"{max(nfq - 1, 0)} 期",
            "900 多个观测": f"{max(nqc - 1, 1) * 31 // 100 * 100:,} 多个观测"}
    fields = ("econ", "invest", "why", "standard", "src", "fail", "risk")
    for v in DOC.values():
        for f in fields:
            if isinstance(v.get(f), str):
                for a, b in reps.items():
                    v[f] = v[f].replace(a, b)
        # 注意：不能写成「对每个 x 遍历 reps 再收集」——那会把每条步骤复制 4 份，
        # 而且每份只替换了一个词。必须先对单条字符串做完所有替换。
        def _rep(x: str) -> str:
            for a, b in reps.items():
                x = x.replace(a, b)
            return x

        v["steps"] = [_rep(x) for x in v.get("steps", [])]


_localize_periods()
