def _periods_text() -> str:
    try:
        import canon as _cn
        n = len(_cn.quarters())
        return f"{n} 期" if n else "全样本期"
    except Exception:
        return "全样本期"


_NQ_TXT = None


def _localize_periods() -> None:
    global _NQ_TXT
    if _NQ_TXT is None:
        _NQ_TXT = _periods_text()
    if _NQ_TXT == "31 期":
        return                      # 期数没变，不必动
    for v in ITEMS.values():
        for f in ("meaning", "principle", "formula", "source", "econ", "invest", "misuse"):
            if isinstance(v.get(f), str):
                v[f] = v[f].replace("31 期", _NQ_TXT)
        v["steps"] = [str(s).replace("31 期", _NQ_TXT) for s in v.get("steps", [])]
        v["threshold"] = [(str(a).replace("31 期", _NQ_TXT),
                           str(b).replace("31 期", _NQ_TXT), c)
                          for a, b, c in v.get("threshold", [])]


