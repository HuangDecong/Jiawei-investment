def compact_table(color: dict) -> str:
    """分类总表：一屏看完所有指标（供方法页）。"""
    rows = []
    for cat in CATS:
        items = [v for v in ITEMS.values() if v["cat"] == cat]
        if not items:
            continue
        rows.append(
            f'<tr><td colspan="3" style="padding:5px 6px;background:{color["panel"]};'
            f'font-weight:700;font-size:11px;border-top:1px solid {color["line"]}">{cat}</td></tr>')
        for v in items:
            rows.append(
                f'<tr><td style="padding:3px 6px;border-top:1px solid {color["grid"]};'
                f'font-size:11px;white-space:nowrap"><b>{v["name"]}</b></td>'
                f'<td style="padding:3px 6px;border-top:1px solid {color["grid"]};'
                f'font-size:10.5px;color:#37485C">{v["meaning"]}</td>'
                f'<td style="padding:3px 6px;border-top:1px solid {color["grid"]};'
                f'font-size:10px;color:{color["text_dim"]}">{v.get("unit","—")}</td></tr>')
    return ('<table style="width:100%;border-collapse:collapse">'
            + "".join(rows) + "</table>")


