"""指标词典：每个指标的含义、原理、公式、计算过程、阈值、标准来源、经济内容、投资含义。

为什么单独一个模块
------------------
指标解释写在页面里，会随页面改版丢失；写在代码注释里，用户看不到。
本模块是**唯一事实源**：侧边栏速查、图表悬浮说明、方法页都从这里取，
改一处全站同步。

每条记录固定九段（缺一段就算没写完）：
    meaning   一句话含义（外行也能懂）
    principle 原理：这个数在度量什么、为什么这样度量
    formula   公式（纯文本 + 上下标用 Unicode，避免 HTML 转义问题）
    steps     计算过程（逐步，可照着手算）
    threshold 阈值表 [(区间, 判读, 该做什么)]
    source    标准来源（法规 / 文献 / 自建，必须区分）
    econ      反映的经济内容
    invest    投资含义
    misuse    常见误用（这条最能防止误判）
"""
